#!/usr/bin/env python3
"""Build src/payload_catalog.js for the Relapse pldmgr edition.

Reads the evoX-CoreOS payload list (json/payloads.json - download fresh from
https://nexgen999.github.io/evoX-CoreOS/json/payloads.json if needed) and
emits a plain JS file defining window.PS5_PAYLOAD_CATALOG with one entry per
payload:

    { id, name, version, category, group, description, filename, url, sha256 }

- category: the evoX category (derived from local_path for the 26 entries
  that have none)
- group:    WebKitty-style tab (homebrew / tools / loaders / servers / debug)
- url:      absolute https URL (url field, or evoX base + local_path)
- sha256:   evoX checksum (verified against the downloads)

The catalog is embedded in the site so the payload manager works even before
the live JSON is fetched; refresh logic lives in src/ui.js.
"""
import json
import os
import sys
import urllib.request

WORK = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = WORK
EVOX_BASE = "https://nexgen999.github.io/evoX-CoreOS/"
JSON_URL = EVOX_BASE + "json/payloads.json"
LOCAL_JSON = os.path.join(REPO, "evox_payloads.json")  # optional local copy
OUT = os.path.join(REPO, "src", "payload_catalog.js")

FALLBACK_DESC = "Récupéré depuis le stockage local (Interne / Fallback)"

# local_path prefix -> evoX category (for the 26 uncategorized entries)
PATH_CATEGORY = {
    "ps5_audio_utility": "PS5 Audio Utility",
    "PS5_Activation": "PS5 Activation",
    "PS5_Beta": "PS5 Beta",
    "PS5_Cheat": "PS5 Cheat",
    "ps5_dns": "PS5 Dns",
    "ps5_emulator": "PS5 Emulator",
    "ps5_fan": "PS5 Fan",
    "ps5_file_explorer": "PS5 File Explorer",
    "ps5_freeshop": "PS5 Freeshop",
    "ps5_game_dump": "PS5 Game Dump",
    "ps5_hen_loader": "PS5 HEN Loader",
    "ps5_kstuff": "PS5 Kstuff",
    "ps5_linux": "PS5 Linux",
    "ps5_pad_utility": "PS5 Pad Utility",
    "ps5_pkg_tool": "PS5 Pkg Tool",
    "ps5_remote": "PS5 Remote",
    "PS5_Overlay": "PS5 Overlay",
    "ps5_sdk_debug": "PS5 Sdk Debug",
    "ps5_server": "PS5 Server",
    "ps5_themes-avatars": "PS5 Themes-Avatars",
    "ps5_utility": "PS5 Utility",
    "ps5_video_player": "PS5 Video Player",
    "ps5-webkit-autoloader": "Ps5-Webkit-Autoloader",
}

# evoX category -> WebKitty-style tab group
CATEGORY_GROUP = {
    "PS5 Emulator": "homebrew",
    "PS5 Video Player": "homebrew",
    "PS5 Audio Utility": "homebrew",
    "PS5 Themes-Avatars": "homebrew",
    "PS5 Freeshop": "homebrew",
    "PS5 Saves": "homebrew",
    "PS5 Cheat": "homebrew",
    "PS5 Remote": "homebrew",
    "PS5 Activation": "homebrew",
    "PS5 Utility": "tools",
    "PS5 Pad Utility": "tools",
    "PS5 Fan": "tools",
    "PS5 File Explorer": "tools",
    "PS5 Pkg Tool": "tools",
    "PS5 Dns": "tools",
    "PS5 Game Dump": "tools",
    "PS5 HEN Loader": "loaders",
    "PS5 Kstuff": "loaders",
    "PS5 Overlay": "loaders",
    "Ps5-Webkit-Autoloader": "loaders",
    "PS5 Beta": "loaders",
    "PS5 Linux": "loaders",
    "PS5 Server": "servers",
    "PS5 Sdk Debug": "debug",
}


def load_payloads():
    if os.path.exists(LOCAL_JSON):
        with open(LOCAL_JSON, encoding="utf-8") as f:
            return json.load(f)["payloads"]
    with urllib.request.urlopen(JSON_URL, timeout=30) as r:
        return json.load(r)["payloads"]


def build():
    payloads = load_payloads()
    entries = []
    for i, p in enumerate(payloads):
        url = p.get("url") or (EVOX_BASE + p["local_path"])
        category = p.get("category") or ""
        if not category:
            prefix = p["local_path"].split("/")[1]
            category = PATH_CATEGORY.get(prefix, "PS5 Utility")
        group = CATEGORY_GROUP.get(category, "tools")
        desc = p.get("description") or ""
        if desc == FALLBACK_DESC or not desc:
            desc = category + " payload, hosted by evoX-CoreOS"
        entries.append({
            "id": "p%d" % i,
            "name": p["name"],
            "version": p.get("version", ""),
            "category": category,
            "group": group,
            "description": desc,
            "filename": p.get("filename", "payload.elf"),
            "url": url,
            "sha256": p.get("checksum", ""),
        })

    counts = {}
    for e in entries:
        counts[e["group"]] = counts.get(e["group"], 0) + 1

    lines = []
    lines.append("/* Auto-generated by scripts/build_payload_catalog.py - do not edit by hand.")
    lines.append(" * Payload catalog for the built-in payload manager: every payload from")
    lines.append(" * https://nexgen999.github.io/evoX-CoreOS/json/payloads.json")
    lines.append(" * (%d payloads). URLs point at the evoX-CoreOS host (CORS enabled)." % len(entries))
    lines.append(" * src/ui.js refreshes this list from the live JSON when the network is up.")
    lines.append(" */")
    lines.append("window.PS5_PAYLOAD_CATALOG = {")
    lines.append('  source: "evoX-CoreOS",')
    lines.append('  sourceUrl: "%s",' % JSON_URL)
    lines.append("  count: %d," % len(entries))
    lines.append("  groups: %s," % json.dumps(counts, sort_keys=True))
    lines.append("  entries: [")
    for e in entries:
        item = json.dumps(e, ensure_ascii=False, sort_keys=True)
        lines.append("    " + item + ",")
    lines.append("  ],")
    lines.append("};")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d payloads, groups %s" % (OUT, len(entries), counts))


if __name__ == "__main__":
    sys.exit(build())
