#!/usr/bin/env python3
"""Generate src/site_files.js - the canonical list of files that make up the
website, used by src/ps5_site_cache.js to cache the site onto the PS5
(/data/relapse-site). Paths are "./"-prefixed to match the localStorage
mirror keys used by the bootstrap in index.html, so a plain-http offline
boot can cache the site with zero network.
"""
import os
import sys

import os

# repo root = the parent of this script's scripts/ folder
WORK = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TEXT_FIXED = ["./index.html", "./sw.js"]

def main():
    text = list(TEXT_FIXED)
    binaries = []

    src = sorted(
        os.path.relpath(os.path.join(root, name), WORK).replace(os.sep, "/")
        for root, _, names in os.walk(os.path.join(WORK, "src"))
        for name in names if name.endswith(".js")
    )
    text += ["./" + p for p in src]

    offsets = sorted(
        os.path.relpath(os.path.join(root, name), WORK).replace(os.sep, "/")
        for root, _, names in os.walk(os.path.join(WORK, "offsets"))
        for name in names if name.endswith(".js")
    )
    text += ["./" + p for p in offsets]

    payloads = sorted(
        os.path.relpath(os.path.join(root, name), WORK).replace(os.sep, "/")
        for root, _, names in os.walk(os.path.join(WORK, "payloads"))
        for name in names
    )
    binaries += ["./" + p for p in payloads]

    def js_list(items):
        return "[" + ", ".join('"%s"' % i for i in items) + "]" if items else "[]"

    js = (
        "/* Auto-generated by scripts/build_site_files.py - do not edit by hand.\n"
        " * The files that make up this website; src/ps5_site_cache.js writes\n"
        " * every one of them to /data/relapse-site when you tap \"Cache site to\n"
        " * PS5\", and sitesrv serves them from console storage on port 12423.\n"
        " */\n"
        "window.SITE_FILES = {\n"
        "  text: %s,\n"
        "  binaries: %s,\n"
        "};\n" % (js_list(text), js_list(binaries))
    )
    dst = os.path.join(WORK, "src", "site_files.js")
    for _ in range(2):
        # two passes: the second one includes the freshly written file itself
        with open(dst, "w") as f:
            f.write(js)
        if "./src/site_files.js" in text:
            break
        src = sorted(set(src) | {"src/site_files.js"})
        text = list(TEXT_FIXED) + ["./" + p for p in src] + ["./" + p for p in offsets]
        js = (
            "/* Auto-generated by scripts/build_site_files.py - do not edit by hand.\n"
            " * The files that make up this website; src/ps5_site_cache.js writes\n"
            " * every one of them to /data/relapse-site when you tap \"Cache site to\n"
            " * PS5\", and sitesrv serves them from console storage on port 12423.\n"
            " */\n"
            "window.SITE_FILES = {\n"
            "  text: %s,\n"
            "  binaries: %s,\n"
            "};\n" % (js_list(text), js_list(binaries))
        )
    print("site_files.js: %d text files, %d binaries -> %s" %
          (len(text), len(binaries), dst))
    assert "./src/site_files.js" in text, "self-include failed"

if __name__ == "__main__":
    sys.exit(main())
