#!/usr/bin/env python3
"""Generate src/payload_data.js: base64-embedded payloads for the Relapse page.

Embeds every binary the exploit AUTO-loads - the elfldr daemon and the kexp
kernel shellcode - so src/payload_cache.js can mirror both into the PS5
browser localStorage the moment the page opens, and the kernel stage can
start elfldr with zero network access. Nothing else auto-loads: every
manager payload (pldmgr included) is fetched on demand from the evoX-CoreOS
catalog by src/main.js.
"""
import base64
import hashlib
import json
import re
import sys

import os

# repo root = the parent of this script's scripts/ folder
WORK = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (name, version, file, path, is_elf, optional)
#   - elfldr: the port-9021 ELF loader daemon, auto-loaded by the chain
#   - kexp:   the kernel shellcode
#   - sitesrv: the on-console site server (port 12423). OPTIONAL: embedded
#     only when payloads/sitesrv.elf exists (build it with ps5-payload-sdk,
#     see sitesrv-src/README.md). Without it the page still works - the
#     "Cache site to PS5" button then explains what is missing.
import os

PAYLOADS = [
    ("elfldr", "13.60", "elfldr-ps5-1360.elf", WORK + "/payloads/elfldr-ps5-1360.elf", True, False),
    ("kexp", "2026-05-25", "kexp_2026_05_25.bin", WORK + "/payloads/kexp_2026_05_25.bin", False, False),
]
if os.path.exists(WORK + "/payloads/sitesrv.elf"):
    PAYLOADS.append(("sitesrv", "1.0", "sitesrv.elf", WORK + "/payloads/sitesrv.elf", True, False))
else:
    print("note: payloads/sitesrv.elf not found - sitesrv NOT embedded")
    print("      (build it: cd sitesrv-src && make, then re-run this script)")
DST = WORK + "/src/payload_data.js"

metas = {}
blocks = []
for name, version, fname, path, is_elf, optional in PAYLOADS:
    data = open(path, "rb").read()
    if is_elf and data[:4] != b"\x7fELF":
        sys.exit(name + ": not an ELF file")
    sha = hashlib.sha256(data).hexdigest()
    metas[name] = {
        "version": version,
        "file": fname,
        "bytes": len(data),
        "sha256": sha,
    }
    b64 = base64.b64encode(data).decode("ascii")
    chunks = [b64[i:i + 1000] for i in range(0, len(b64), 1000)]
    # Chunk join MUST use an explicit trailing "+" - adjacent string literals
    # across newlines are split into separate statements by ASI.
    block = ('window.PS5_PAYLOADS.b64["%s"] =\n' % name) + "\n".join(
        '  "%s"%s' % (c, " +" if i < len(chunks) - 1 else "")
        for i, c in enumerate(chunks)
    ) + ";\n"
    blocks.append(block)
    print("%-7s v%-10s %9d bytes -> %10d b64 chars, sha256 %s..." %
          (name, version, len(data), len(b64), sha[:16]))

meta_js = json.dumps(metas, indent=2).replace("\n", "\n  ")
js = (
    "/* Auto-generated by scripts/build_payload_js.py - do not edit by hand.\n"
    " * Embedded payloads for the Relapse page: elfldr (port-9021 ELF loader\n"
    " * daemon - the only payload that auto-loads) and the kexp kernel shellcode.\n"
    " * src/payload_cache.js mirrors both into PS5 localStorage as soon as the\n"
    " * page opens; every manager payload (pldmgr included) comes on demand\n"
    " * from the evoX-CoreOS catalog via src/main.js.\n"
    " */\n"
    "window.PS5_PAYLOADS = {\n  meta: " + meta_js + ",\n  b64: {}\n};\n\n"
    + "\n".join(blocks)
)
open(DST, "w").write(js)

# Roundtrip: split on the assignment markers, join the quoted chunks per
# payload, decode and compare sha256 against the source files.
text = open(DST).read()
parts = re.split(r'window\.PS5_PAYLOADS\.b64\["(\w+)"\] =', text)
assert len(parts) == 1 + 2 * len(PAYLOADS), "unexpected payload_data.js layout"
for i, (name, version, fname, path, is_elf, optional) in enumerate(PAYLOADS):
    assert parts[1 + 2 * i] == name, "block order mismatch for " + name
    body = parts[2 + 2 * i]
    joined = "".join(re.findall(r'"([^"]*)"', body))
    decoded = base64.b64decode(joined)
    orig = open(path, "rb").read()
    assert len(decoded) == len(orig), name + ": length mismatch"
    assert hashlib.sha256(decoded).hexdigest() == hashlib.sha256(orig).hexdigest(), \
        name + ": roundtrip mismatch"
print("payload_data.js written: %d payloads embedded, all roundtrip OK" % len(PAYLOADS))
